export function getMood(id: string | null | undefined): Mood {
  return MOODS.find((m) => m.id === id) ?? MOODS[3];
}

export function pickRandomScript(mood: Mood): string[] {
  const index = Math.floor(Math.random() * mood.scripts.length);
  return mood.scripts[index];
}
